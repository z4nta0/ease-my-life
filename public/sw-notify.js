// #region Notification Click Handler

/**
 * sw-notify.js = Notification Click Handler
 *
 * @summary
 * Closes the clicked notification, then brings the app forward: it focuses
 * an app window that is already open anywhere, and opens a new one only as a
 * last resort. The daily list has already been generated by the time the
 * notification exists, so this only ever navigates. It posts no message to
 * the page, and nothing it does can trigger a second generation. The work is
 * passed to waitUntil, so the browser keeps the worker alive until the window
 * is focused or opened.
 *
 * @author z4nta0 <https://github.com/z4nta0>
 *
 * @param notEveObj - Notification Event Object: The notificationclick event
 *                    the browser fires on the service worker.
 *
 * @returns This function does not return anything.
 *
 * @example
 * ```ts
 * ( notEveObj ) => { ... } // => void
 * ```
 *
*/

self.addEventListener( 'notificationclick', ( notEveObj ) => { // What: Notification Click Listener. Why: Only the service worker can respond to a click on a notification it owns. How: This registers the handler for every notificationclick event.


	notEveObj.notification.close(); // What: Notification Close Call. Why: A clicked notification should leave the tray. How: This closes the one that was clicked.



	const focWinFun = async () => { // What: Focus Window Function. Why: The app should come forward in a window that already exists before a new one is opened. How: This focuses the first app window that can be focused, otherwise opens the app's root, and resolves with that window.


		const winCliArr = await self.clients.matchAll( { includeUncontrolled : true, type : 'window' } ); // What: Window Client Array. Why: The app may already be open in a window this worker doesn't control yet. How: This lists every app window, controlled or not.


		for ( const winCliObj of winCliArr ) { // What: Window Client Loop. Why: The first window that can take focus is the one to bring forward. How: This walks the windows in the order the browser lists them.


			if ( 'focus' in winCliObj ) return winCliObj.focus(); // What: Focus Window Guard. Why: An open app window is reused rather than duplicated. How: This focuses the first window that supports it and stops there.


		}



		if ( self.clients.openWindow ) return self.clients.openWindow( '/' ); // What: Open Window Guard. Why: With no app window to focus, the click should still open the app. How: This opens the app's root where the browser supports it.


	};


	notEveObj.waitUntil( focWinFun() ); // What: Wait Until Call. Why: The browser may stop the worker before the window is focused or opened. How: This keeps the worker alive until focWinFun's promise settles.


} );

// #endregion Notification Click Handler


