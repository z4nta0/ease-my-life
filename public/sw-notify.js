// Injected into the generated service worker via workbox.importScripts (see
// vite.config.js). Everything else in the SW is Workbox's precache handling;
// this file adds only the notification click behaviour.
//
// Notifications shown with registration.showNotification() are owned by the
// service worker, not the page, so their click has to be handled here. Without
// this listener, tapping a notification on Android does nothing at all.
self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  // Focus an existing window if the app is already open anywhere; only open a
  // new one as a last resort. The daily list has ALREADY been generated by the
  // time this notification exists, so this must never do more than navigate —
  // no message is posted to the page and nothing triggers a second generation.
  event.waitUntil((async () => {
    const all = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    for (const client of all) {
      if ('focus' in client) return client.focus();
    }
    if (self.clients.openWindow) return self.clients.openWindow('/');
  })());
});
