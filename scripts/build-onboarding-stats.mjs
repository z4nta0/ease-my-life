// One-off precompute script — NOT part of the app build or runtime. Run it
// manually (`node scripts/build-onboarding-stats.mjs`) whenever the sample
// picker/item/reminder data in src/onboarding-seed-data.js changes, to
// regenerate src/onboarding-stats-data.js.
//
// Why this exists: the Welcome Tour seeds sample pickers on a fresh install
// and wants Stats to already look like a real year of history, not a blank
// slate. Generating that live (~365 days x a handful of pickers) is cheap
// CPU-wise, but the user explicitly wants it precomputed and shipped as
// static data rather than computed at install time. The wrinkle: a year of
// "history" is meaningless without a "today" to be relative to, and this
// script's "today" (whenever it happens to run) is NOT the same day someone
// actually installs the app. So instead of baking absolute dates, every row
// stores a `daysAgo` offset; onboarding.jsx's seeding effect converts those
// back to real ISO dates relative to the ACTUAL current date at seed time —
// a trivial, instant per-row map, not a regeneration.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { OB_EXAMPLE, OB_EXTRA_PICKERS, OB_TASKS } from '../src/onboarding-seed-data.js';
import { weightedPick, seedIsoDay, buildPickLog } from '../src/seed.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// ── Reconstruct the pickers/items exactly as store.jsx's addPicker() would
// create them live, so the simulated history lines up with what the app
// actually seeds (see addPicker in src/store.jsx for the source of truth
// this mirrors). ──
const PICKER_DEFS = [OB_EXAMPLE, ...OB_EXTRA_PICKERS];
const pickers = PICKER_DEFS.map((p) => ({
  id: p.id, group: p.group, name: p.name, mode: p.mode,
  easeMin: 10, easeMax: 20, threshold: 100,
  daysOfWeek: [0, 1, 2, 3, 4, 5, 6],
}));
const items = PICKER_DEFS.flatMap((p) => p.items.map((it) => {
  const isDown = p.mode === 'ease-down';
  const isEase = p.mode === 'ease-up' || isDown;
  return {
    id: it.id, pickerId: p.id, name: it.name,
    weight: isDown ? 1 : (it.weight || 1),
    value: it.value != null ? it.value : (isDown ? 100 : 0),
    ...(isEase ? { easeMin: it.easeMin ?? 7, easeMax: it.easeMax ?? 14 } : {}),
  };
}));

// No vacation history for the sample pickers.
const onVac = () => false;
const { rows } = buildPickLog(items, pickers, onVac, 365);

const today = new Date();
today.setHours(0, 0, 0, 0);
const dayIndexFromIso = (iso) => {
  const [y, m, d] = iso.split('-').map(Number);
  return Math.floor(Date.UTC(y, m - 1, d) / 86400000);
};
const todayIdx = dayIndexFromIso(seedIsoDay(today));
const daysAgoOf = (iso) => todayIdx - dayIndexFromIso(iso);

const pickLog = rows.map((r) => {
  let h = null, m = null;
  if (r.completedAt) {
    const d = new Date(r.completedAt);
    h = d.getHours(); m = d.getMinutes();
  }
  return {
    daysAgo: daysAgoOf(r.date),
    pickerId: r.pickerId, itemId: r.itemId,
    itemName: r.itemName, pickerName: r.pickerName, group: r.group,
    done: r.done, h, m, source: r.source,
    ...(r.outcome ? { outcome: r.outcome } : {}),
    ...(r.depletedEnd ? { depletedEnd: true } : {}),
  };
});

// ── Reminder history: only "Take trash out for pickup" (tk_ob_trash) gets
// history — it's recurring (weekly, Mondays). "Pick up prescription" is
// one-time and hasn't been completed yet in this fresh install, so it has
// no history to seed. ~52 Mondays across a year; the large majority
// completed, a handful skipped, matching the dev SEED's own realism ratio. ──
const trashTask = OB_TASKS.find((t) => t.id === 'tk_ob_trash');
const mondays = [];
for (let back = 1; back <= 370; back++) {
  const d = new Date(today);
  d.setDate(today.getDate() - back);
  if (d.getDay() === 1) mondays.push(back);
}
const reminderLog = [];
const reminderSkipLog = [];
for (const daysAgo of mondays) {
  const h = 8, m = 10 + Math.floor(Math.random() * 40);
  if (Math.random() < 0.88) {
    reminderLog.push({ taskId: trashTask.id, name: trashTask.name, type: 'recurring', daysAgo, h, m });
  } else {
    reminderSkipLog.push({ taskId: trashTask.id, name: trashTask.name, type: 'recurring', daysAgo, h: 7, m: 45 });
  }
}

const out = `// AUTO-GENERATED by scripts/build-onboarding-stats.mjs — do not hand-edit.
// Regenerate with \`node scripts/build-onboarding-stats.mjs\` whenever
// src/onboarding-seed-data.js changes. See that script for why this data
// is precomputed and stored as day-offsets rather than absolute dates.
//
// Shape: pickLog rows mirror state.pickLog (minus id/eid/completedAt, which
// onboarding.jsx's seeding effect fills in at hydration time from daysAgo/h/m).
// reminderLog / reminderSkipLog rows mirror state.reminderLog / .reminderSkipLog
// the same way (minus rowId/completedAt or skippedAt).
export const ONBOARDING_STATS = ${JSON.stringify({ pickLog, reminderLog, reminderSkipLog }, null, 2)};
`;

const outPath = path.join(__dirname, '..', 'src', 'onboarding-stats-data.js');
writeFileSync(outPath, out);
console.log(`Wrote ${pickLog.length} pickLog rows, ${reminderLog.length} reminderLog rows, ${reminderSkipLog.length} reminderSkipLog rows to ${outPath}`);
